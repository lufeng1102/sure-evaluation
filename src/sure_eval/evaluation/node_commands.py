def _slugify(name: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "_", name.strip().lower()).strip("_")
    return slug or "node"


def _default_for(manifest: dict[str, Any]) -> list[str]:
    result: list[str] = []
    for profile in (manifest.get("profiles") or {}).values():
        if isinstance(profile, dict):
            result.extend(str(item) for item in (profile.get("default_for") or ()))
    return result


def list_nodes() -> dict[str, Any]:
    """Enumerate every discovered node (builtin + entry point)."""

    registry = get_registry()
    nodes: list[dict[str, Any]] = []
    for node_id in registry.iter_node_ids():
        reg = registry.resolve(node_id)
        nodes.append(
            {
                "node_id": node_id,
                "stage": reg.stage,
                "version": reg.version,
                "source": reg.source,
                "selectors": dict(reg.selectors),
                "default_for": _default_for(reg.manifest),
                "has_build": callable(reg.build),
                "has_node_env": reg.node_env is not None,
            }
        )
    return {"schema": NODE_LIST_SCHEMA, "count": len(nodes), "nodes": nodes}


def create_node(
    name: str,
    *,
    stage: str,
    output_dir: str | Path,
) -> dict[str, Any]:
    """Scaffold a single-file external node package under ``output_dir``."""

    slug = _slugify(name)
    stage = stage.strip().lower()
    if not stage:
        raise ValueError("--stage is required, e.g. normalization or scoring")
    node_id = f"{stage}/{slug}"
    module_path = f"sure_eval_node_{slug}"
    selectors = {"normalizer": slug} if stage == "normalization" else {"scorer": slug}

    package_dir = Path(output_dir) / slug
    module_dir = package_dir / "src" / module_path
    module_dir.mkdir(parents=True, exist_ok=True)

    pyproject = _TEMPLATE_PYPROJECT.format(
        package_name=f"sure-eval-node-{slug}",
        node_id=node_id,
        module_path=module_path,
    )
    node_py = _TEMPLATE_NODE_PY.format(
        stage=stage,
        name=name,
        node_id=node_id,
        selectors=selectors,
    )
    plugin_manifest = _TEMPLATE_PLUGIN_MANIFEST.format(
        package_name=f"sure-eval-node-{slug}",
        module_path=module_path,
    )

    files: list[str] = []
    for path, content in (
        (package_dir / "pyproject.toml", pyproject),
        (package_dir / "sure_eval_plugin.yaml", plugin_manifest),
        (module_dir / "__init__.py", _TEMPLATE_INIT),
        (module_dir / "node.py", node_py),
    ):
        path.write_text(content, encoding="utf-8")
        files.append(str(path))

    return {
        "schema": "sure-eval/node-create@v1",
        "name": name,
        "node_id": node_id,
        "stage": stage,
        "package_dir": str(package_dir),
        "module_path": module_path,
        "files": files,
        "install_hint": f"pip install -e {package_dir}",
        "plugin_add_hint": f"sure-eval plugin add {package_dir}",
    }
